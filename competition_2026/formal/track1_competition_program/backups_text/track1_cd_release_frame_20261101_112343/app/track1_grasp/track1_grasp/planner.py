def euler_to_matrix(rpy: Sequence[float]) -> np.ndarray:
    """R = Rz(yaw) @ Ry(pitch) @ Rx(roll)."""
    roll, pitch, yaw = (float(v) for v in rpy)
    cr, sr = np.cos(roll), np.sin(roll)
    cp, sp = np.cos(pitch), np.sin(pitch)
    cy, sy = np.cos(yaw), np.sin(yaw)
    rx = np.array([[1.0, 0.0, 0.0], [0.0, cr, -sr], [0.0, sr, cr]])
    ry = np.array([[cp, 0.0, sp], [0.0, 1.0, 0.0], [-sp, 0.0, cp]])
    rz = np.array([[cy, -sy, 0.0], [sy, cy, 0.0], [0.0, 0.0, 1.0]])
    return rz @ ry @ rx


def transform_from_xyz_rpy(xyz: Sequence[float], rpy: Sequence[float]) -> np.ndarray:
    transform = np.eye(4)
    transform[:3, :3] = euler_to_matrix(rpy)
    transform[:3, 3] = np.asarray(xyz, dtype=float)
    return transform


def transform_point(transform: np.ndarray, point: Sequence[float]) -> np.ndarray:
    source = np.asarray(point, dtype=float)
    if source.shape != (3,):
        raise ValueError("point must be a 3-vector")
    return transform[:3, :3] @ source + transform[:3, 3]


@dataclass(frozen=True)
class AdaptiveGraspCandidate:
    """One object-relative grasp orientation and its complete motion plan."""

    plan: MotionPlan
    yaw_offset_deg: float
    orientation_change_rad: float
    object_center_base_xyz: tuple[float, float, float]
    major_axis_base: tuple[float, float, float]
    pitch_offset_deg: float = 0.0
    #: Deterministic horizontal PCA major/minor frame used for a learned
    #: point-specific object offset.  The major vector is sign-canonicalised so
    #: a PCA sign flip cannot mirror the minor-axis correction.
    major_axis_horizontal_base: tuple[float, float] | None = None
    #: Learned ``[major, minor]`` jaw-tip offset in that object frame.
    jaw_tip_object_offset_m: tuple[float, float] | None = None
    #: Jaw-tip point generated by the selected flange pose and tip offset.
    #: This is diagnostic only; the commanded RobotMove pose remains ``plan``.
    commanded_jaw_tip_base_xyz: tuple[float, float, float] | None = None


