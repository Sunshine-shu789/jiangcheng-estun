def load_extrinsics(path: str | Path) -> np.ndarray:
    with open(path, "r", encoding="utf-8") as handle:
        payload = yaml.safe_load(handle) or {}
    if "matrix" in payload:
        matrix = np.asarray(payload["matrix"], dtype=float)
        if matrix.shape != (4, 4):
            raise ValueError("extrinsics matrix must be 4x4")
        return matrix
    if "xyz" not in payload:
        raise ValueError("extrinsics file needs matrix or xyz")
    return transform_from_xyz_rpy(
        payload["xyz"], payload.get("rpy", (0.0, 0.0, 0.0))
    )


def _rotation_z(angle_rad: float) -> np.ndarray:
    cosine = float(np.cos(angle_rad))
    sine = float(np.sin(angle_rad))
    return np.array(
        [
            [cosine, -sine, 0.0],
            [sine, cosine, 0.0],
            [0.0, 0.0, 1.0],
        ],
        dtype=float,
    )


class PosePlanner:
    """Convert detections into bounded, collision-unaware Cartesian waypoints.

    The first version intentionally leaves collision-aware planning to MoveIt
    or the controller's Cartesian planner.  It provides the same plan object
    to either backend, so the orchestration remains stable.
    """

    def __init__(self, config: Track1Config, log=None) -> None:
        self.config = config
        self._log = log or (lambda message: None)
        self._extrinsics: np.ndarray | None = None

    def _camera_transform(self) -> np.ndarray:
        if self._extrinsics is not None:
            return self._extrinsics
        path = self.config.pose.extrinsics_file
        if not path:
            raise RuntimeError(
                "camera-to-base calibration is missing; install/calibrate the "
                "camera or enable pose.fallback_camera_to_base for mock mode"
            )
        self._extrinsics = load_extrinsics(path)
        self._log(f"[pose] loaded camera transform from {path}")
        return self._extrinsics

    def base_camera_transform(self, robot_state: RobotState) -> np.ndarray:
        """Return the audited ``base_flange @ flange_camera`` transform."""

        return self._base_flange_transform(robot_state) @ self._camera_transform()

    def detection_to_base(self, detection: Detection, robot_state: RobotState) -> np.ndarray:
        if self.config.pose.use_detection_base_xyz and detection.base_xyz is not None:
            return np.asarray(detection.base_xyz, dtype=float)
        if detection.camera_xyz is None:
            raise ValueError("detection has neither base_xyz nor camera_xyz")

        camera_xyz = np.asarray(detection.camera_xyz, dtype=float)
        if self.config.pose.fallback_camera_to_base:
            offset = np.asarray(
                self.config.pose.fixed_camera_to_base_xyz, dtype=float
            )
            return camera_xyz + offset

        transform = self._camera_transform()
        if self.config.pose.camera_frame == "base":
            return transform_point(transform, camera_xyz)
        if robot_state.pose is None:
            raise RuntimeError("flange camera mode needs a current robot pose")
        base_flange = transform_from_xyz_rpy(robot_state.pose.xyz, robot_state.pose.rpy)
        return transform_point(base_flange @ transform, camera_xyz)

    def _check_workspace(self, pose: Pose) -> None:
        low = np.asarray(self.config.motion.workspace_min, dtype=float)
        high = np.asarray(self.config.motion.workspace_max, dtype=float)
        margin = float(self.config.motion.workspace_margin)
        point = np.asarray(pose.xyz, dtype=float)
        if np.any(point < low + margin) or np.any(point > high - margin):
            raise ValueError(
                f"pose {tuple(round(float(v), 4) for v in point)} "
                "is outside the configured workspace"
            )

    def _orientation(self, robot_state: RobotState) -> tuple[float, float, float]:
        if self.config.motion.orientation == "fixed":
            return self.config.motion.fixed_rpy
        if robot_state.pose is None:
            raise RuntimeError("orientation=current needs a current robot pose")
        return robot_state.pose.rpy

    def _base_flange_transform(self, robot_state: RobotState) -> np.ndarray:
        """Return T_base_flange from the controller's declared pose semantics."""

        if robot_state.pose is None:
            raise RuntimeError("adaptive grasp needs a current robot pose")
        base_controller = transform_from_xyz_rpy(
            robot_state.pose.xyz,
            robot_state.pose.rpy,
        )
        frame = self.config.pose.robot_pose_frame
        if frame == "flange":
            return base_controller
        if frame == "tcp":
            flange_tcp = np.eye(4)
            flange_tcp[:3, 3] = np.asarray(
                self.config.pose.tcp_offset_m,
                dtype=float,
            )
            return base_controller @ np.linalg.inv(flange_tcp)
        raise RuntimeError(
            "adaptive grasp requires pose.robot_pose_frame=flange or tcp"
        )

    @staticmethod
    def _jaw_tip_xyz_for_flange_pose(
        pose: Pose,
        offset_flange_m: np.ndarray | None,
    ) -> np.ndarray:
        """Return the closed-jaw low point generated by one flange pose."""

        flange_xyz = np.asarray(pose.xyz, dtype=float)
        if offset_flange_m is None:
            return flange_xyz.copy()
        return flange_xyz + euler_to_matrix(pose.rpy) @ offset_flange_m

    def validate_grasp_safety_plan(self, plan: MotionPlan) -> GraspSafetyReport:
        """Validate the complete C/D grasp envelope before any actuator moves.

        The visual target is a jaw-tip point.  Every commanded waypoint remains
        a controller/flange pose; this method converts each pose back to its
        generated jaw-tip point before checking table clearance.  Optional
        limits are useful during dry-run, while the live configuration rejects
        missing limits during startup.
        """

        safety = self.config.motion.grasp_safety
        waypoints = plan.ordered_waypoints()
        if not waypoints:
            raise RuntimeError("grasp safety check received a plan with no waypoints")
        for waypoint_name, pose in waypoints:
            if pose is None:
                raise RuntimeError(
                    f"grasp safety plan is missing waypoint {waypoint_name!r}"
                )
            values = np.asarray((*pose.xyz, *pose.rpy), dtype=float)
            if values.shape != (6,) or not np.all(np.isfinite(values)):
                raise RuntimeError(
                    f"grasp safety waypoint {waypoint_name!r} must contain "
                    "finite XYZ and RPY values"
                )

        if not safety.enabled:
            return GraspSafetyReport(
                enabled=False,
                waypoint_count=len(waypoints),
            )

        if self.config.pose.robot_pose_frame != "flange":
            raise RuntimeError(
                "C/D grasp safety requires controller poses in the flange frame; "
                f"got pose.robot_pose_frame={self.config.pose.robot_pose_frame!r}"
            )
        configured_offset = self.config.pose.gripper_tip_offset_flange_m
        if configured_offset is None and safety.require_flange_tip_offset:
            raise RuntimeError(
                "C/D grasp safety requires "
                "pose.gripper_tip_offset_flange_m"
            )
        tip_limit_configured = any(
            value is not None
            for value in (
                safety.minimum_grasp_tip_z_m,
                safety.maximum_grasp_tip_z_m,
                safety.minimum_route_tip_z_m,
                safety.maximum_route_tip_z_m,
            )
        )
        if configured_offset is None and tip_limit_configured:
            raise RuntimeError(
                "C/D jaw-tip Z limits require "
                "pose.gripper_tip_offset_flange_m"
            )
        tip_offset = (
            None
            if configured_offset is None
            else np.asarray(configured_offset, dtype=float)
        )
        if tip_offset is not None and (
            tip_offset.shape != (3,) or not np.all(np.isfinite(tip_offset))
        ):
            raise RuntimeError(
                "pose.gripper_tip_offset_flange_m must be a finite 3-vector"
            )

        expected_grasp_rpy = self.config.motion.grasp_rpy
        if expected_grasp_rpy is None:
            raise RuntimeError(
                "C/D grasp safety requires an explicit motion.grasp_rpy"
            )
        expected_grasp_rpy_array = np.asarray(expected_grasp_rpy, dtype=float)
        if expected_grasp_rpy_array.shape != (3,) or not np.all(
            np.isfinite(expected_grasp_rpy_array)
        ):
            raise RuntimeError("motion.grasp_rpy must be a finite 3-vector")
        if not np.allclose(
            plan.grasp_pose.rpy,
            expected_grasp_rpy_array,
            atol=1e-9,
            rtol=0.0,
        ):
            raise RuntimeError(
                "planned grasp orientation differs from the fixed "
                "motion.grasp_rpy"
            )

        flange_z_values: list[float] = []
        tip_z_values: list[float] = []
        maximum_tool_tilt_deg = 0.0
        maximum_horizontal_reach_m = 0.0
        for waypoint_name, pose in waypoints:
            flange_xyz = np.asarray(pose.xyz, dtype=float)
            tip_xyz = self._jaw_tip_xyz_for_flange_pose(pose, tip_offset)
            tool_z = euler_to_matrix(pose.rpy)[:, 2]
            if not np.all(np.isfinite(tool_z)):
                raise RuntimeError(
                    f"grasp safety waypoint {waypoint_name!r} has a "
                    "non-finite tool Z axis"
                )
            if safety.require_tool_down and float(tool_z[2]) >= 0.0:
                raise RuntimeError(
                    f"grasp safety waypoint {waypoint_name!r} tool Z is not "
                    f"downward: ({tool_z[0]:.9f}, {tool_z[1]:.9f}, "
                    f"{tool_z[2]:.9f})"
                )
            tilt_deg = float(
                np.degrees(
                    np.arccos(
                        float(np.clip(-tool_z[2], -1.0, 1.0))
                    )
                )
            )
            if not np.isfinite(tilt_deg):
                raise RuntimeError(
                    f"grasp safety waypoint {waypoint_name!r} produced a "
                    "non-finite tool tilt"
                )
            maximum_tool_tilt_deg = max(maximum_tool_tilt_deg, tilt_deg)
            flange_z_values.append(float(flange_xyz[2]))
            tip_z_values.append(float(tip_xyz[2]))
            waypoint_reach = max(
                float(np.linalg.norm(flange_xyz[:2])),
                float(np.linalg.norm(tip_xyz[:2])),
            )
            maximum_horizontal_reach_m = max(
                maximum_horizontal_reach_m,
                waypoint_reach,
            )
            if (
                safety.maximum_horizontal_reach_m is not None
                and waypoint_reach > float(safety.maximum_horizontal_reach_m)
            ):
                raise RuntimeError(
                    f"grasp safety waypoint {waypoint_name!r} horizontal "
                    f"reach {waypoint_reach:.6f} m exceeds "
                    f"{float(safety.maximum_horizontal_reach_m):.6f} m"
                )

        if (
            safety.maximum_tool_tilt_deg is not None
            and maximum_tool_tilt_deg > float(safety.maximum_tool_tilt_deg)
        ):
            raise RuntimeError(
                f"grasp safety maximum tool tilt {maximum_tool_tilt_deg:.6f} "
                "deg exceeds "
                f"{float(safety.maximum_tool_tilt_deg):.6f} deg"
            )

        grasp_flange_xyz = np.asarray(plan.grasp_pose.xyz, dtype=float)
        grasp_tip_xyz = self._jaw_tip_xyz_for_flange_pose(
            plan.grasp_pose,
            tip_offset,
        )
        for value, minimum, maximum, label in (
            (
                float(grasp_flange_xyz[2]),
                safety.minimum_grasp_flange_z_m,
                safety.maximum_grasp_flange_z_m,
                "grasp flange Z",
            ),
            (
                float(grasp_tip_xyz[2]),
                safety.minimum_grasp_tip_z_m,
                safety.maximum_grasp_tip_z_m,
                "grasp jaw-tip Z",
            ),
        ):
            if minimum is not None and value < float(minimum):
                raise RuntimeError(
                    f"{label} {value:.6f} m is below {float(minimum):.6f} m"
                )
            if maximum is not None and value > float(maximum):
                raise RuntimeError(
                    f"{label} {value:.6f} m is above {float(maximum):.6f} m"
                )

        route_minimum_flange_z = min(flange_z_values)
        route_maximum_flange_z = max(flange_z_values)
        route_minimum_tip_z = min(tip_z_values)
        route_maximum_tip_z = max(tip_z_values)
        for value, minimum, maximum, label in (
            (
                route_minimum_flange_z,
                safety.minimum_route_flange_z_m,
                None,
                "minimum route flange Z",
            ),
            (
                route_maximum_flange_z,
                None,
                safety.maximum_route_flange_z_m,
                "maximum route flange Z",
            ),
            (
                route_minimum_tip_z,
                safety.minimum_route_tip_z_m,
                None,
                "minimum route jaw-tip Z",
            ),
            (
                route_maximum_tip_z,
                None,
                safety.maximum_route_tip_z_m,
                "maximum route jaw-tip Z",
            ),
        ):
            if minimum is not None and value < float(minimum):
                raise RuntimeError(
                    f"{label} {value:.6f} m is below {float(minimum):.6f} m"
                )
            if maximum is not None and value > float(maximum):
                raise RuntimeError(
                    f"{label} {value:.6f} m is above {float(maximum):.6f} m"
                )

        pregrasp_xyz = np.asarray(plan.pregrasp_pose.xyz, dtype=float)
        approach_height_m = float(pregrasp_xyz[2] - grasp_flange_xyz[2])
        if not np.isfinite(approach_height_m) or approach_height_m <= 0.0:
            raise RuntimeError(
                "pregrasp must be above the flange grasp pose; "
                f"approach_height={approach_height_m:.6f} m"
            )
        if (
            safety.minimum_approach_height_m is not None
            and approach_height_m < float(safety.minimum_approach_height_m)
        ):
            raise RuntimeError(
                f"pregrasp approach height {approach_height_m:.6f} m is below "
                f"{float(safety.minimum_approach_height_m):.6f} m"
            )
        if (
            safety.maximum_approach_height_m is not None
            and approach_height_m > float(safety.maximum_approach_height_m)
        ):
            raise RuntimeError(
                f"pregrasp approach height {approach_height_m:.6f} m is above "
                f"{float(safety.maximum_approach_height_m):.6f} m"
            )
        approach_xy_error_m = float(
            np.linalg.norm(grasp_flange_xyz[:2] - pregrasp_xyz[:2])
        )
        if (
            safety.maximum_approach_xy_error_m is not None
            and approach_xy_error_m
            > float(safety.maximum_approach_xy_error_m)
        ):
            raise RuntimeError(
                f"pregrasp XY alignment error {approach_xy_error_m:.6f} m "
                f"exceeds {float(safety.maximum_approach_xy_error_m):.6f} m"
            )

        return GraspSafetyReport(
            enabled=True,
            waypoint_count=len(waypoints),
            flange_tip_offset_m=(
                None
                if tip_offset is None
                else tuple(float(value) for value in tip_offset)
            ),
            grasp_flange_xyz_m=tuple(float(value) for value in grasp_flange_xyz),
            grasp_tip_xyz_m=tuple(float(value) for value in grasp_tip_xyz),
            minimum_route_flange_z_m=route_minimum_flange_z,
            maximum_route_flange_z_m=route_maximum_flange_z,
            minimum_route_tip_z_m=route_minimum_tip_z,
            maximum_route_tip_z_m=route_maximum_tip_z,
            approach_height_m=approach_height_m,
            approach_xy_error_m=approach_xy_error_m,
            maximum_tool_tilt_deg=maximum_tool_tilt_deg,
            maximum_horizontal_reach_m=maximum_horizontal_reach_m,
        )

    def _adaptive_object_geometry(
        self,
        detection: Detection,
        robot_state: RobotState,
    ) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
        if detection.object_center_camera_xyz is None:
            raise ValueError("adaptive grasp needs object_center_camera_xyz")
        if detection.major_axis_camera is None:
            raise ValueError("adaptive grasp needs major_axis_camera")
        adaptive = self.config.adaptive_inverse
        if detection.pose_confidence is None:
            raise ValueError("adaptive grasp needs pose_confidence")
        if float(detection.pose_confidence) < float(adaptive.min_pose_confidence):
            raise ValueError(
                "object pose confidence "
                f"{float(detection.pose_confidence):.3f} is below "
                f"{float(adaptive.min_pose_confidence):.3f}"
            )

        base_flange = self._base_flange_transform(robot_state)
        flange_camera = self._camera_transform()
        base_camera = base_flange @ flange_camera
        center_base = transform_point(
            base_camera,
            detection.object_center_camera_xyz,
        )
        major_axis_base = (
            base_camera[:3, :3]
            @ np.asarray(detection.major_axis_camera, dtype=float)
        )
        major_norm = float(np.linalg.norm(major_axis_base))
        if not np.isfinite(major_norm) or major_norm <= 1e-12:
            raise ValueError("object major axis is not finite after transform")
        major_axis_base = major_axis_base / major_norm
        horizontal_norm = float(np.linalg.norm(major_axis_base[:2]))
        if horizontal_norm <= 1e-6:
            raise ValueError(
                "object major axis has no usable horizontal projection"
            )
        return center_base, major_axis_base, base_flange

    @staticmethod
    def _wrap_angle(angle: float) -> float:
        return float(np.arctan2(np.sin(angle), np.cos(angle)))

    @staticmethod
    def _wrap_axis_delta(angle: float) -> float:
        """Return the shortest equivalent delta between undirected axes."""

        return float(
            (float(angle) + np.pi * 0.5) % np.pi - np.pi * 0.5
        )

    def plan_box_relative_candidates(
        self,
        detection: Detection,
        frame: Frame,
        robot_state: RobotState,
        pose: BoxPoseEstimate,
        layout: BoxPointLayout,
        *,
        place_name: str = "",
        return_to_pick: bool = True,
        box_clearance_template: BoxClearanceConfig | None = None,
    ) -> tuple[BoxPointGraspCandidate, ...]:
        """Plan all five grasps from one fitted, stable RGB-D frame.

        This path deliberately does not inspect the detection's PCA heading.
        Box-local +X and +Y are the fitted ``NW->NE`` and ``SW->NW`` corners;
        every candidate uses the corresponding yaw and a tool Z axis pointing
        vertically down.  The caller must precheck every returned route before
        any item matching, gripper event or motion command.
        """

        if not self.config.adaptive_inverse.box_relative_five_point.enabled:
            raise ValueError("box-relative five-point planning is not enabled")
        if not return_to_pick:
            raise ValueError(
                "box-relative five-point planning requires return_to_pick=True"
            )
        capture = frame.capture_robot_state
        if capture is None:
            raise ValueError(
                "box-relative planning requires robot feedback captured before "
                "and after the exact RGB-D frame"
            )
        if pose.frame_id != frame.frame_id:
            raise ValueError(
                "box pose frame_id does not match the exact planning frame"
            )
        if robot_state.pose is None:
            raise ValueError("box-relative planning needs current robot FK")

        tip_offset_flange = self.config.pose.gripper_tip_offset_flange_m
        if tip_offset_flange is None:
            raise ValueError(
                "box-relative planning requires "
                "pose.gripper_tip_offset_flange_m"
            )
        tip_offset_flange_array = np.asarray(tip_offset_flange, dtype=float)
        if tip_offset_flange_array.shape != (3,) or not np.all(
            np.isfinite(tip_offset_flange_array)
        ):
            raise ValueError(
                "pose.gripper_tip_offset_flange_m must be a finite 3-vector"
            )

        # This is the only allowed eye-in-hand chain.  The fitted box pose,
        # item centre and all five grasp points share it for this frame.
        base_camera = self.base_camera_transform(capture.before)
        if base_camera.shape != (4, 4) or not np.all(np.isfinite(base_camera)):
            raise ValueError("capture camera transform is malformed")

        clearance_template = (
            box_clearance_template
            if box_clearance_template is not None
            else self.config.adaptive_inverse.box_clearance
        )
        dynamic_clearance = dynamic_box_clearance(clearance_template, pose)
        jaw_tip_clearance_m = float(
            self.config.adaptive_inverse.candidates.jaw_tip_clearance_m
        )
        approach_height_m = self.config.adaptive_inverse.candidates.approach_height_m
        if approach_height_m is None:
            approach_height_m = self.config.task_b.vertical_grasp_approach_height_m

        candidates: list[BoxPointGraspCandidate] = []
        for point in layout.points:
            point_xy = np.asarray(
                self._box_local_xy_to_base_for_pose(point.local_xy_m, pose),
                dtype=float,
            )
            jaw_tip_base = np.array(
                (
                    point_xy[0],
                    point_xy[1],
                    float(pose.center_base_xyz_m[2]) + jaw_tip_clearance_m,
                ),
                dtype=float,
            )
            candidate_rpy = (
                float(np.pi),
                0.0,
                float(pose.yaw_rad),
            )
            candidate_rotation = euler_to_matrix(candidate_rpy)
            flange_target = jaw_tip_base - candidate_rotation @ tip_offset_flange_array
            anchor_pose = Pose(
                tuple(float(value) for value in flange_target),
                candidate_rpy,
            )
            candidate_name = place_name or point.name
            plan = self.plan(
                detection,
                robot_state,
                place_name=candidate_name,
                return_to_pick=True,
                grasp_rpy=candidate_rpy,
                task_b_anchor_pose=anchor_pose,
                grasp_xyz_override_m=tuple(float(value) for value in flange_target),
                vertical_grasp_descent=True,
                vertical_grasp_approach_height_m=float(approach_height_m),
                use_visual_grasp_z=True,
            )
            candidates.append(
                BoxPointGraspCandidate(
                    box_point_name=point.name,
                    plan=plan,
                    box_pose=pose,
                    dynamic_box_clearance=dynamic_clearance,
                )
            )
            self._log(
                "[box-five-point-plan] point="
                f"{point.name} jaw_tip_base=({jaw_tip_base[0]:.6f}, "
                f"{jaw_tip_base[1]:.6f}, {jaw_tip_base[2]:.6f}) "
                f"flange_target=({flange_target[0]:.6f}, "
                f"{flange_target[1]:.6f}, {flange_target[2]:.6f}) "
                f"rpy=({candidate_rpy[0]:.6f}, {candidate_rpy[1]:.6f}, "
                f"{candidate_rpy[2]:.6f})"
            )
        return tuple(candidates)

    @staticmethod
    def _box_local_xy_to_base_for_pose(
        local_xy_m: Sequence[float],
        pose: BoxPoseEstimate,
    ) -> tuple[float, float]:
        local = np.asarray(local_xy_m, dtype=float)
        if local.shape != (2,) or not np.all(np.isfinite(local)):
            raise ValueError("box-local grasp point must be a finite 2-vector")
        cosine = float(np.cos(pose.yaw_rad))
        sine = float(np.sin(pose.yaw_rad))
        rotation = np.array(((cosine, -sine), (sine, cosine)), dtype=float)
        base = rotation @ local + np.asarray(pose.center_base_xy_m, dtype=float)
        return (float(base[0]), float(base[1]))

    def plan_adaptive_candidates(
        self,
        detection: Detection,
        robot_state: RobotState,
        *,
        place_name: str = "",
        return_to_pick: bool = True,
        grasp_z_m: float | None = None,
        grasp_rpy: Sequence[float] | None = None,
        task_b_anchor_pose: Pose | None = None,
        vertical_grasp_approach_height_m: float | None = None,
        jaw_tip_object_offset_m: Sequence[float] | None = None,
    ) -> tuple[AdaptiveGraspCandidate, ...]:
        """Plan object-relative grasp orientation candidates without motion.

        Candidate headings rotate the operator-taught orientation about base Z
        so the taught tool X axis aligns with the observed object major axis.
        When ``lock_taught_orientation`` is enabled, vision supplies only the
        grasp XY and the exact taught RPY is retained for every candidate.
        Legacy arbitrary-placement mode accepts only a tool Z axis pointing
        exactly down.  The opt-in ``tilted_visual_grasp`` mode instead permits
        the configured pitch candidates to tilt the tool and approaches along
        each candidate's own tool Z axis.  Every candidate still retains the
        same current visual jaw-tip point, and the pipeline checks the complete
        six-waypoint route before selection or any command.

        ``jaw_tip_object_offset_m`` is an optional learned ``[major, minor]``
        offset from the detected object centre to the actual jaw-tip grasp
        point.  It is expressed in a sign-canonicalised horizontal PCA frame,
        so the same taught sample remains valid when PCA flips the major-axis
        sign.  Fixed-point live grasping can require this sample explicitly;
        omitting it then fails before any route or motion command.
        """

        adaptive = self.config.adaptive_inverse
        if not adaptive.enabled:
            raise ValueError("adaptive inverse planning is not enabled")
        if not return_to_pick:
            raise ValueError(
                "adaptive Task B planning requires return_to_pick=True"
            )

        center_base, major_axis_base, _base_flange = (
            self._adaptive_object_geometry(detection, robot_state)
        )
        # PCA axes are undirected.  Canonicalise the horizontal major axis before
        # constructing the minor axis; otherwise the learned minor offset would
        # point to opposite sides of the banana when PCA flips its sign.
        major_xy = np.asarray(major_axis_base[:2], dtype=float)
        major_xy_norm = float(np.linalg.norm(major_xy))
        if not np.isfinite(major_xy_norm) or major_xy_norm <= 1e-12:
            raise ValueError("object major axis has no finite horizontal projection")
        major_xy = major_xy / major_xy_norm
        if major_xy[0] < -1e-12 or (
            abs(float(major_xy[0])) <= 1e-12 and major_xy[1] < 0.0
        ):
            major_xy = -major_xy
        minor_xy = np.array((-major_xy[1], major_xy[0]), dtype=float)

        learned_offset: np.ndarray | None = None
        if jaw_tip_object_offset_m is not None:
            if isinstance(jaw_tip_object_offset_m, (str, bytes)):
                raise RuntimeError(
                    "jaw_tip_object_offset_m must be a finite 2-vector"
                )
            learned_offset = np.asarray(jaw_tip_object_offset_m, dtype=float)
            if learned_offset.shape != (2,) or not np.all(
                np.isfinite(learned_offset)
            ):
                raise RuntimeError(
                    "jaw_tip_object_offset_m must be a finite 2-vector"
                )
            if float(np.max(np.abs(learned_offset))) > 0.10 + 1e-12:
                raise RuntimeError(
                    "jaw_tip_object_offset_m exceeds the 0.10 m safety limit"
                )
        if (
            bool(adaptive.candidates.require_jaw_tip_object_offset)
            and learned_offset is None
        ):
            raise RuntimeError(
                "fixed-point adaptive grasping requires a learned "
                "jaw-tip object offset"
            )
        if learned_offset is not None and (
            self.config.pose.gripper_tip_offset_flange_m is None
        ):
            raise RuntimeError(
                "jaw_tip_object_offset_m requires "
                "pose.gripper_tip_offset_flange_m"
            )

        taught_rpy = tuple(
            float(value)
            for value in (
                grasp_rpy
                if grasp_rpy is not None
                else (
                    task_b_anchor_pose.rpy
                    if task_b_anchor_pose is not None
                    else (
                        self.config.motion.grasp_rpy
                        if self.config.motion.grasp_rpy is not None
                        else self._orientation(robot_state)
                    )
                )
            )
        )
        taught_rotation = euler_to_matrix(taught_rpy)
        taught_x_yaw = float(
            np.arctan2(taught_rotation[1, 0], taught_rotation[0, 0])
        )
        observed_yaw = float(np.arctan2(major_xy[1], major_xy[0]))
        principal_delta = self._wrap_axis_delta(
            self._wrap_angle(
                observed_yaw
                - taught_x_yaw
                + np.radians(
                    float(adaptive.candidates.axis_alignment_offset_deg)
                )
            )
        )

        effective_approach_height = float(
            adaptive.candidates.approach_height_m
            if adaptive.candidates.approach_height_m is not None
            else (
                self.config.task_b.vertical_grasp_approach_height_m
                if vertical_grasp_approach_height_m is None
                else float(vertical_grasp_approach_height_m)
            )
        )
        effective_grasp_z = (
            None
            if adaptive.candidates.use_visual_grasp_z
            else grasp_z_m
        )
        anchor = task_b_anchor_pose
        if anchor is None:
            # The vertical candidate planner only needs a marker pose.  Use a
            # conservative high point above the current/observed location; the
            # actual pregrasp Z remains grasp Z plus the configured clearance.
            base_z = (
                float(robot_state.pose.xyz[2])
                if robot_state.pose is not None
                else float(center_base[2]) + effective_approach_height
            )
            anchor = Pose(
                (
                    float(center_base[0]),
                    float(center_base[1]),
                    max(base_z, float(center_base[2]) + effective_approach_height),
                ),
                taught_rpy,
            )

        candidates: list[AdaptiveGraspCandidate] = []
        seen_rotations: list[np.ndarray] = []
        candidate_failures: list[str] = []
        max_orientation_change_rad = np.radians(
            float(adaptive.candidates.max_orientation_change_deg)
        )
        tip_offset_flange = self.config.pose.gripper_tip_offset_flange_m
        if adaptive.candidates.use_visual_grasp_z and tip_offset_flange is None:
            raise RuntimeError(
                "visual grasp requires pose.gripper_tip_offset_flange_m"
            )
        minimum_grasp_flange_z_m = (
            adaptive.candidates.minimum_grasp_flange_z_m
        )
        if minimum_grasp_flange_z_m is not None:
            minimum_grasp_flange_z_m = float(minimum_grasp_flange_z_m)
            if not np.isfinite(minimum_grasp_flange_z_m):
                raise RuntimeError(
                    "minimum grasp flange Z must be finite when configured"
                )
        commanded_tip_base = center_base.copy()
        if learned_offset is not None:
            commanded_tip_base[:2] = center_base[:2] + (
                float(learned_offset[0]) * major_xy
                + float(learned_offset[1]) * minor_xy
            )
        commanded_tip_base[2] += float(
            adaptive.candidates.jaw_tip_clearance_m
        )
        lock_taught_orientation = bool(
            adaptive.candidates.lock_taught_orientation
        )
        pitch_offsets_deg = (
            adaptive.candidates.taught_pitch_offsets_deg
            if lock_taught_orientation
            and adaptive.candidates.taught_pitch_offsets_deg
            else adaptive.candidates.pitch_offsets_deg
        )

        # Yaw is the outer loop so the primary object-axis alignment is tried
        # before a less-favourable J6 heading.  Legacy arbitrary placement
        # permits only the zero pitch entry; opt-in tilted placement lets the
        # configured pitch list choose safe approach directions.  Strict
        # fixed-point mode bypasses both loops' rotations and uses the exact
        # taught RPY, while keeping the visual XY and fixed-Z pipeline.
        for configured_yaw_deg in adaptive.candidates.yaw_offsets_deg:
            if lock_taught_orientation:
                delta = 0.0
                heading_rotation = taught_rotation
                heading_roll, heading_pitch, heading_yaw = taught_rpy
            else:
                delta = self._wrap_angle(
                    principal_delta + np.radians(float(configured_yaw_deg))
                )
                heading_rotation = _rotation_z(delta) @ taught_rotation
                heading_roll, heading_pitch, heading_yaw = matrix_to_rpy(
                    heading_rotation
                )
            for configured_pitch_deg in pitch_offsets_deg:
                pitch_delta = np.radians(float(configured_pitch_deg))
                if lock_taught_orientation:
                    # Hold the taught roll/yaw and test only a tightly bounded
                    # ZYX pitch branch.  Each branch is still subject to every
                    # downstream workspace, IK, step, acceleration and
                    # singularity gate.
                    candidate_rpy = (
                        float(taught_rpy[0]),
                        float(taught_rpy[1]) + float(pitch_delta),
                        float(taught_rpy[2]),
                    )
                else:
                    candidate_rpy = (
                        float(heading_roll),
                        float(heading_pitch) + float(pitch_delta),
                        float(heading_yaw),
                    )
                if abs(candidate_rpy[1]) > np.pi * 0.5 + 1e-9:
                    candidate_failures.append(
                        f"yaw {float(configured_yaw_deg):.2f} deg, "
                        f"pitch {float(configured_pitch_deg):.2f} deg exceeds "
                        "the usable ZYX pitch range"
                    )
                    continue
                candidate_rotation = euler_to_matrix(candidate_rpy)
                if adaptive.arbitrary_placement:
                    tool_z = candidate_rotation[:, 2]
                    if adaptive.tilted_visual_grasp:
                        # A top approach must still point downward.  Candidates
                        # outside the lower hemisphere are skipped rather than
                        # weakening any downstream IK or collision check.
                        if float(tool_z[2]) >= -1e-6:
                            candidate_failures.append(
                                f"yaw {float(configured_yaw_deg):.2f} deg, "
                                f"pitch {float(configured_pitch_deg):.2f} deg "
                                "does not point the tool axis downward"
                            )
                            continue
                    else:
                        vertical_error = float(
                            np.linalg.norm(
                                tool_z - np.array((0.0, 0.0, -1.0))
                            )
                        )
                        if vertical_error > 1e-7:
                            raise ValueError(
                                "arbitrary-placement grasp candidate must keep "
                                "tool Z vertical down; "
                                f"yaw_offset={np.degrees(delta):.3f} deg "
                                f"pitch_offset={float(configured_pitch_deg):.3f} "
                                f"deg tool_z=({tool_z[0]:.9f}, "
                                f"{tool_z[1]:.9f}, {tool_z[2]:.9f})"
                            )
                orientation_change_rad = rotation_angle_error(
                    candidate_rotation, taught_rotation
                )
                if (
                    orientation_change_rad
                    > max_orientation_change_rad + 1e-12
                ):
                    candidate_failures.append(
                        f"yaw {float(configured_yaw_deg):.2f} deg, "
                        f"pitch {float(configured_pitch_deg):.2f} deg gives "
                        f"{np.degrees(orientation_change_rad):.2f} deg total "
                        "orientation change, above the configured limit"
                    )
                    continue
                rotation_vector = rotation_matrix_to_vector(candidate_rotation)
                if any(
                    np.linalg.norm(rotation_vector - seen) < 1e-7
                    for seen in seen_rotations
                ):
                    continue

                grasp_flange_xyz = center_base.copy()
                tip_offset_base: np.ndarray | None = None
                if adaptive.candidates.use_visual_grasp_z or learned_offset is not None:
                    assert tip_offset_flange is not None
                    tip_offset_base = (
                        candidate_rotation
                        @ np.asarray(tip_offset_flange, dtype=float)
                    )
                    # Convert the intended jaw-tip point into the flange target
                    # commanded by RobotMove.  With learned object coordinates,
                    # the XY correction follows the current observed object,
                    # while the taught per-point flange Z remains authoritative
                    # unless visual-Z mode is explicitly enabled.
                    grasp_flange_xyz = commanded_tip_base - tip_offset_base
                    self._log(
                        "[adaptive-plan] yaw_offset="
                        f"{np.degrees(delta):.3f} deg pitch_offset="
                        f"{float(configured_pitch_deg):.3f} deg "
                        "object_center_base="
                        f"({center_base[0]:.6f}, {center_base[1]:.6f}, "
                        f"{center_base[2]:.6f}) m; major_axis_xy="
                        f"({major_xy[0]:.6f}, {major_xy[1]:.6f}); "
                        "jaw_tip_object_offset_m="
                        + (
                            "None"
                            if learned_offset is None
                            else f"({learned_offset[0]:.6f}, "
                            f"{learned_offset[1]:.6f}) m"
                        )
                        + "; commanded_tip_base="
                        f"({commanded_tip_base[0]:.6f}, "
                        f"{commanded_tip_base[1]:.6f}, "
                        f"{commanded_tip_base[2]:.6f}) m; flange_target="
                        f"({grasp_flange_xyz[0]:.6f}, "
                        f"{grasp_flange_xyz[1]:.6f}, "
                        f"{grasp_flange_xyz[2]:.6f}) m; "
                        f"tip_offset_base=({tip_offset_base[0]:.6f}, "
                        f"{tip_offset_base[1]:.6f}, "
                        f"{tip_offset_base[2]:.6f}) m"
                    )
                try:
                    clearance = check_box_clearance(
                        adaptive.box_clearance,
                        flange_xy_m=grasp_flange_xyz[:2],
                        rotation=candidate_rotation,
                    )
                except (ValueError, RuntimeError) as exc:
                    candidate_failures.append(
                        f"yaw {float(configured_yaw_deg):.2f} deg, "
                        f"pitch {float(configured_pitch_deg):.2f} deg: "
                        f"box-clearance check failed closed: {exc}"
                    )
                    self._log(
                        "[adaptive-plan] candidate rejected by box clearance: "
                        f"yaw={np.degrees(delta):.3f} deg "
                        f"pitch={float(configured_pitch_deg):.3f} deg "
                        f"error={exc}"
                    )
                    continue
                if not clearance.allowed:
                    candidate_failures.append(
                        f"yaw {float(configured_yaw_deg):.2f} deg, "
                        f"pitch {float(configured_pitch_deg):.2f} deg: "
                        f"box clearance rejected candidate: {clearance.reason}"
                    )
                    self._log(
                        "[adaptive-plan] candidate rejected by box clearance: "
                        f"yaw={np.degrees(delta):.3f} deg "
                        f"pitch={float(configured_pitch_deg):.3f} deg "
                        f"reason={clearance.reason}"
                    )
                    continue
                try:
                    if adaptive.tilted_visual_grasp:
                        plan = self.plan(
                            detection,
                            robot_state,
                            place_name=place_name,
                            return_to_pick=True,
                            grasp_z_m=effective_grasp_z,
                            grasp_rpy=candidate_rpy,
                            task_b_anchor_pose=anchor,
                            grasp_xyz_override_m=grasp_flange_xyz,
                            tool_axis_grasp_descent=True,
                            tool_axis_approach_height_m=(
                                effective_approach_height
                            ),
                            use_visual_grasp_z=(
                                adaptive.candidates.use_visual_grasp_z
                            ),
                        )
                    else:
                        plan = self.plan(
                            detection,
                            robot_state,
                            place_name=place_name,
                            return_to_pick=True,
                            grasp_z_m=effective_grasp_z,
                            grasp_rpy=candidate_rpy,
                            task_b_anchor_pose=anchor,
                            grasp_xyz_override_m=grasp_flange_xyz,
                            vertical_grasp_descent=True,
                            vertical_grasp_approach_height_m=(
                                effective_approach_height
                            ),
                            use_visual_grasp_z=(
                                adaptive.candidates.use_visual_grasp_z
                            ),
                        )
                except (ValueError, RuntimeError) as exc:
                    candidate_failures.append(
                        f"yaw {float(configured_yaw_deg):.2f} deg, "
                        f"pitch {float(configured_pitch_deg):.2f} deg: {exc}"
                    )
                    self._log(
                        "[adaptive-plan] candidate rejected before route "
                        "precheck: "
                        f"yaw={np.degrees(delta):.3f} deg "
                        f"pitch={float(configured_pitch_deg):.3f} deg "
                        f"error={exc}"
                    )
                    continue
                if minimum_grasp_flange_z_m is not None:
                    planned_flange_z_m = float(plan.grasp_pose.xyz[2])
                    if planned_flange_z_m < minimum_grasp_flange_z_m - 1e-9:
                        failure = (
                            "planned grasp flange Z "
                            f"{planned_flange_z_m:.6f} m is below the hard "
                            "minimum "
                            f"{minimum_grasp_flange_z_m:.6f} m"
                        )
                        candidate_failures.append(
                            f"yaw {float(configured_yaw_deg):.2f} deg, "
                            f"pitch {float(configured_pitch_deg):.2f} deg: "
                            f"{failure}"
                        )
                        self._log(
                            "[adaptive-plan] candidate rejected by grasp-depth "
                            "floor: "
                            f"yaw={np.degrees(delta):.3f} deg "
                            f"pitch={float(configured_pitch_deg):.3f} deg "
                            f"planned_flange_z={planned_flange_z_m:.6f} m "
                            f"minimum={minimum_grasp_flange_z_m:.6f} m"
                        )
                        continue
                planned_jaw_tip_base = (
                    np.asarray(plan.grasp_pose.xyz, dtype=float)
                    + candidate_rotation
                    @ np.asarray(tip_offset_flange, dtype=float)
                    if tip_offset_flange is not None
                    else None
                )
                candidates.append(
                    AdaptiveGraspCandidate(
                        plan=plan,
                        yaw_offset_deg=float(np.degrees(delta)),
                        pitch_offset_deg=float(configured_pitch_deg),
                        orientation_change_rad=float(orientation_change_rad),
                        object_center_base_xyz=tuple(
                            float(value) for value in center_base
                        ),
                        major_axis_base=tuple(
                            float(value) for value in major_axis_base
                        ),
                        major_axis_horizontal_base=(
                            float(major_xy[0]),
                            float(major_xy[1]),
                        ),
                        jaw_tip_object_offset_m=(
                            None
                            if learned_offset is None
                            else (
                                float(learned_offset[0]),
                                float(learned_offset[1]),
                            )
                        ),
                        commanded_jaw_tip_base_xyz=(
                            None
                            if planned_jaw_tip_base is None
                            else tuple(
                                float(value) for value in planned_jaw_tip_base
                            )
                        ),
                    )
                )
                seen_rotations.append(rotation_vector)
                if len(candidates) >= int(adaptive.candidates.max_count):
                    break
            if len(candidates) >= int(adaptive.candidates.max_count):
                break

        if not candidates:
            detail = "; ".join(candidate_failures[:5])
            raise ValueError(
                "no adaptive grasp candidate remained after geometry checks"
                + (f": {detail}" if detail else "")
            )
        return tuple(candidates)

    def plan(
        self,
        detection: Detection,
        robot_state: RobotState,
        *,
        place_pose: Sequence[float] | None = None,
        place_name: str = "",
        return_to_pick: bool = False,
        grasp_z_m: float | None = None,
        grasp_rpy: Sequence[float] | None = None,
        task_b_anchor_pose: Pose | None = None,
        grasp_xy_from_observation: bool = False,
        grasp_xy_m: Sequence[float] | None = None,
        grasp_xy_offset_m: Sequence[float] | None = None,
        grasp_xyz_override_m: Sequence[float] | None = None,
        vertical_grasp_descent: bool = False,
        vertical_grasp_approach_height_m: float | None = None,
        tool_axis_grasp_descent: bool = False,
        tool_axis_approach_height_m: float | None = None,
        use_visual_grasp_z: bool = False,
        grasp_target_is_jaw_tip: bool = False,
    ) -> MotionPlan:
        """Build the Cartesian waypoints for one pick cycle.

        ``return_to_pick`` creates an in-place pick-and-return plan: transfer,
        release and retreat all stay above the observed grasp XY coordinates,
        and the object is released at the same grasp pose from which it was
        lifted.  This is the required Task B behaviour.

        ``task_b_anchor_pose`` optionally supplies the operator-taught
        observation pose for one Task B point.  When present, every high
        waypoint (pregrasp, lift, transfer and retreat) uses that complete
        Cartesian pose.  By default grasp and release still use the visual XY
        and the point-specific grasp height/orientation.  With
        ``grasp_xy_from_observation`` enabled they instead retain the taught
        observation anchor XY, producing a straight vertical descent from that
        validated column.  Returning to a known
        well-conditioned anchor avoids asking the IK solver to carry a large
        combined translation/orientation change through a near-singular
        wrist configuration.  ``grasp_xy_m`` supplies an explicit taught grasp
        column instead; in that case the high waypoints stay at the observation
        anchor height but move directly above that column, with the final
        descent performed at the grasp orientation.  ``grasp_xy_offset_m``
        applies a final flange/tool-frame XY correction after selecting the
        visual, observation, or explicit XY.  The correction is rotated into
        the base frame by the final grasp RPY; only its base X/Y components are
        applied so the verified grasp Z stays fixed.  All high, grasp and
        release waypoints then use the corrected column.
        ``vertical_grasp_descent``
        applies the same column lock even when XY comes from vision or the
        observation anchor, and also uses the final grasp orientation at the
        high pose.  Consequently the pregrasp-to-grasp segment has zero lateral
        and zero rotational change.  ``tool_axis_grasp_descent`` is a separate
        opt-in mode for tilted visual grasps: the high pose is offset from the
        grasp flange by the configured distance along the negative final tool
        Z axis.  Release remains exactly at grasp, and lift/transfer/retreat
        return to that tool-axis high pose.

        Without ``return_to_pick``, ``place_pose`` overrides
        ``motion.place_pose`` for this cycle and the object is moved to that
        configured drop pose.  Tasks C/D/E use that legacy mode.
        """
        if task_b_anchor_pose is not None and not return_to_pick:
            raise ValueError(
                "task_b_anchor_pose is only valid with return_to_pick=True"
            )
        if grasp_xy_from_observation and not return_to_pick:
            raise ValueError(
                "grasp_xy_from_observation is only valid with "
                "return_to_pick=True"
            )
        if grasp_xy_from_observation and task_b_anchor_pose is None:
            raise ValueError(
                "grasp_xy_from_observation needs a task_b_anchor_pose"
            )
        if grasp_xy_m is not None:
            if not return_to_pick:
                raise ValueError(
                    "grasp_xy_m is only valid with return_to_pick=True"
                )
            if grasp_xy_from_observation:
                raise ValueError(
                    "grasp_xy_m and grasp_xy_from_observation are mutually "
                    "exclusive"
                )
            if len(grasp_xy_m) != 2 or not all(
                np.isfinite(float(value)) for value in grasp_xy_m
            ):
                raise ValueError("grasp_xy_m must contain two finite values")
        if grasp_xy_offset_m is not None:
            if not return_to_pick:
                raise ValueError(
                    "grasp_xy_offset_m is only valid with return_to_pick=True"
                )
            if len(grasp_xy_offset_m) != 2 or not all(
                np.isfinite(float(value)) for value in grasp_xy_offset_m
            ):
                raise ValueError(
                    "grasp_xy_offset_m must contain two finite values"
                )
        if grasp_xyz_override_m is not None:
            if len(grasp_xyz_override_m) != 3 or not all(
                np.isfinite(float(value)) for value in grasp_xyz_override_m
            ):
                raise ValueError(
                    "grasp_xyz_override_m must contain three finite values"
                )
        if vertical_grasp_descent:
            if not return_to_pick:
                raise ValueError(
                    "vertical_grasp_descent is only valid with "
                    "return_to_pick=True"
                )
            if task_b_anchor_pose is None:
                raise ValueError(
                    "vertical_grasp_descent needs a task_b_anchor_pose"
                )
        if tool_axis_grasp_descent:
            if not return_to_pick:
                raise ValueError(
                    "tool_axis_grasp_descent is only valid with "
                    "return_to_pick=True"
                )
            if vertical_grasp_descent:
                raise ValueError(
                    "tool_axis_grasp_descent and vertical_grasp_descent are "
                    "mutually exclusive"
                )
            if not use_visual_grasp_z:
                raise ValueError(
                    "tool_axis_grasp_descent requires use_visual_grasp_z=True"
                )
        if use_visual_grasp_z and not return_to_pick:
            raise ValueError(
                "use_visual_grasp_z is only valid with return_to_pick=True"
            )
        if grasp_target_is_jaw_tip and use_visual_grasp_z:
            raise ValueError(
                "grasp_target_is_jaw_tip and use_visual_grasp_z are mutually "
                "exclusive; adaptive planning already performs the jaw-tip "
                "conversion"
            )

        base_xyz = (
            np.asarray(grasp_xyz_override_m, dtype=float)
            if grasp_xyz_override_m is not None
            else self.detection_to_base(detection, robot_state)
        )
        rpy = self._orientation(robot_state)
        grasp_xyz = base_xyz.copy()
        if grasp_xy_from_observation:
            assert task_b_anchor_pose is not None
            grasp_xyz[0] = float(task_b_anchor_pose.xyz[0])
            grasp_xyz[1] = float(task_b_anchor_pose.xyz[1])
        elif grasp_xy_m is not None:
            grasp_xyz[0] = float(grasp_xy_m[0])
            grasp_xyz[1] = float(grasp_xy_m[1])
        effective_grasp_rpy = (
            grasp_rpy
            if grasp_rpy is not None
            else self.config.motion.grasp_rpy
        )
        if (
            return_to_pick or grasp_target_is_jaw_tip
        ) and effective_grasp_rpy is not None:
            rpy = tuple(float(v) for v in effective_grasp_rpy)
        if grasp_xy_offset_m is not None:
            flange_xy_offset = np.asarray(grasp_xy_offset_m, dtype=float)
            tool_to_base = euler_to_matrix(rpy)
            base_xy_delta = tool_to_base @ np.array(
                [flange_xy_offset[0], flange_xy_offset[1], 0.0],
                dtype=float,
            )
            # The correction was requested in flange XY.  Preserve the
            # operator-verified grasp height by applying only the rotated base
            # X/Y projection rather than allowing tool tilt to shift base Z.
            grasp_xyz[0] += base_xy_delta[0]
            grasp_xyz[1] += base_xy_delta[1]
            self._log(
                "[plan] flange_xy_offset="
                f"({flange_xy_offset[0]:.6f}, {flange_xy_offset[1]:.6f}) m; "
                "base_xy_delta="
                f"({base_xy_delta[0]:.6f}, {base_xy_delta[1]:.6f}) m; "
                f"base_z_delta_ignored={base_xy_delta[2]:.6f} m"
            )
        effective_grasp_z_m = (
            grasp_z_m
            if grasp_z_m is not None
            else self.config.motion.grasp_z_m
        )
        if use_visual_grasp_z:
            # Adaptive inverse grasping supplies a flange target that has
            # already been derived from the observed jaw-tip point with the
            # selected orientation and ``gripper_tip_offset_flange_m``.  Do not
            # replace it with either the per-point taught height or the global
            # motion default, and do not stack a second fixed Z offset.
            pass
        elif return_to_pick and effective_grasp_z_m is not None:
            # A depth anchor describes the visible object surface, not the TCP
            # pose needed to seat the jaws around it.  Task B may therefore use
            # an operator-verified grasp height while retaining visual XY (or
            # an explicitly selected observation-anchor XY for vertical
            # descent).
            grasp_xyz[2] = float(effective_grasp_z_m)
        else:
            grasp_xyz[2] += float(self.config.motion.grasp_z_offset)
        if grasp_target_is_jaw_tip:
            if effective_grasp_rpy is None:
                raise ValueError(
                    "grasp_target_is_jaw_tip requires an explicit grasp RPY"
                )
            tip_offset = self.config.pose.gripper_tip_offset_flange_m
            if tip_offset is None:
                raise ValueError(
                    "grasp_target_is_jaw_tip requires "
                    "pose.gripper_tip_offset_flange_m"
                )
            tip_offset_array = np.asarray(tip_offset, dtype=float)
            if tip_offset_array.shape != (3,) or not np.all(
                np.isfinite(tip_offset_array)
            ):
                raise ValueError(
                    "pose.gripper_tip_offset_flange_m must be a finite "
                    "3-vector"
                )
            commanded_tip_xyz = grasp_xyz.copy()
            grasp_xyz = commanded_tip_xyz - (
                euler_to_matrix(rpy) @ tip_offset_array
            )
            self._log(
                "[plan] visual jaw-tip target="
                f"{tuple(round(float(value), 6) for value in commanded_tip_xyz)}; "
                "flange="
                f"{tuple(round(float(value), 6) for value in grasp_xyz)}; "
                "tip_offset_flange="
                f"{tuple(round(float(value), 6) for value in tip_offset_array)}"
            )
        grasp_pose = Pose(tuple(float(v) for v in grasp_xyz), rpy)
        task_b_high_pose = task_b_anchor_pose
        if tool_axis_grasp_descent:
            effective_approach_height_m = (
                self.config.adaptive_inverse.candidates.approach_height_m
                if tool_axis_approach_height_m is None
                else float(tool_axis_approach_height_m)
            )
            if (
                effective_approach_height_m is None
                or not np.isfinite(float(effective_approach_height_m))
                or float(effective_approach_height_m) <= 0.0
            ):
                raise ValueError(
                    "tool_axis_approach_height_m must be positive and finite"
                )
            grasp_rotation = euler_to_matrix(rpy)
            tool_z = grasp_rotation[:, 2]
            if not np.all(np.isfinite(tool_z)) or float(tool_z[2]) >= 0.0:
                raise ValueError(
                    "tool-axis grasp requires a finite, downward-pointing tool "
                    f"Z axis; axis=({tool_z[0]:.9f}, {tool_z[1]:.9f}, "
                    f"{tool_z[2]:.9f})"
                )
            high_xyz = grasp_xyz - (
                float(effective_approach_height_m) * tool_z
            )
            task_b_high_pose = Pose(
                tuple(float(value) for value in high_xyz),
                rpy,
            )
        elif task_b_anchor_pose is not None and (
            vertical_grasp_descent or grasp_xy_m is not None
        ):
            # Establish the high pose directly over the final grasp column.
            # For vertical_grasp_descent, use a fixed operator-configured height
            # above the verified grasp Z instead of inheriting the observation
            # height.  Never add a preparatory upward move before the straight
            # descent: after visual confirmation the next motion is directly
            # downward along Z with fixed XY and RPY.
            # The explicit-XY mode retains its historic high-pose calculation.
            if vertical_grasp_descent:
                effective_approach_height_m = (
                    self.config.task_b.vertical_grasp_approach_height_m
                    if vertical_grasp_approach_height_m is None
                    else vertical_grasp_approach_height_m
                )
                if (
                    not np.isfinite(float(effective_approach_height_m))
                    or float(effective_approach_height_m) <= 0.0
                ):
                    raise ValueError(
                        "vertical_grasp_approach_height_m must be positive "
                        "and finite"
                    )
                high_z = float(grasp_xyz[2]) + float(
                    effective_approach_height_m
                )
            else:
                high_z = max(
                    float(task_b_anchor_pose.xyz[2]),
                    float(grasp_xyz[2])
                    + float(self.config.motion.approach_height),
                    float(grasp_xyz[2])
                    + float(self.config.motion.lift_height),
                )
            task_b_high_pose = Pose(
                (float(grasp_xyz[0]), float(grasp_xyz[1]), high_z),
                rpy,
            )

        if return_to_pick and task_b_high_pose is not None:
            pregrasp_pose = task_b_high_pose
            lift_pose = task_b_high_pose
        else:
            pregrasp_pose = Pose(
                (
                    float(grasp_xyz[0]),
                    float(grasp_xyz[1]),
                    float(grasp_xyz[2] + self.config.motion.approach_height),
                ),
                rpy,
            )
            lift_pose = Pose(
                (
                    float(grasp_xyz[0]),
                    float(grasp_xyz[1]),
                    float(grasp_xyz[2] + self.config.motion.lift_height),
                ),
                rpy,
            )

        transfer_pose: Pose | None = None
        release_pose: Pose | None = None
        retreat_pose: Pose | None = None
        if return_to_pick:
            # Do not use the legacy fixed drop pose here.  The object must be
            # returned to the exact XY location where it was observed and
            # grasped.  With a taught observation anchor, lift/transfer/retreat
            # all return to that exact high pose; otherwise retain the historic
            # vertical in-place path for callers without a captured anchor.
            release_xyz = tuple(float(v) for v in grasp_xyz)
            release_pose = Pose(release_xyz, rpy)
            if task_b_high_pose is not None:
                transfer_pose = task_b_high_pose
                retreat_pose = task_b_high_pose
            else:
                transfer_pose = Pose(
                    (
                        release_xyz[0],
                        release_xyz[1],
                        release_xyz[2] + self.config.motion.place_approach_height,
                    ),
                    rpy,
                )
                retreat_pose = Pose(
                    (
                        release_xyz[0],
                        release_xyz[1],
                        release_xyz[2] + self.config.motion.retreat_height,
                    ),
                    rpy,
                )
        else:
            effective_place = (
                place_pose if place_pose is not None else self.config.motion.place_pose
            )
            if effective_place is not None:
                place = effective_place
                place_xyz = tuple(float(v) for v in place[:3])
                place_rpy = tuple(float(v) for v in place[3:6])
                transfer_pose = Pose(
                    (
                        place_xyz[0],
                        place_xyz[1],
                        place_xyz[2] + self.config.motion.place_approach_height,
                    ),
                    place_rpy,
                )
                release_pose = Pose(place_xyz, place_rpy)
                retreat_pose = Pose(
                    (
                        place_xyz[0],
                        place_xyz[1],
                        place_xyz[2] + self.config.motion.retreat_height,
                    ),
                    place_rpy,
                )

        plan = MotionPlan(
            target=detection,
            grasp_pose=grasp_pose,
            pregrasp_pose=pregrasp_pose,
            lift_pose=lift_pose,
            transfer_pose=transfer_pose,
            release_pose=release_pose,
            retreat_pose=retreat_pose,
            place_name=place_name,
        )
        for name, pose in plan.ordered_waypoints():
            try:
                self._check_workspace(pose)
            except ValueError as exc:
                raise ValueError(f"planned waypoint {name!r} rejected: {exc}") from exc
        return plan
